export function AnimatedNumber({ value, decimals = 0, suffix = '' }: { value: number | null | undefined; decimals?: number; suffix?: string }) {
  const target = value ?? 0;
  const [display, setDisplay] = useState(target);

  useEffect(() => {
    let frame = 0;
    const start = display;
    const diff = target - start;
    if (Math.abs(diff) < 0.05) {
      setDisplay(target);
      return;
    }
    const steps = 18;
    let step = 0;
    const tick = () => {
      step += 1;
      const eased = 1 - Math.pow(1 - step / steps, 3);
      setDisplay(start + diff * eased);
      if (step < steps) {
        frame = requestAnimationFrame(tick);
      } else {
        setDisplay(target);
      }
    };
    frame = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(frame);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [target]);

  if (value == null) return <span>—</span>;
  return (
    <span className="tabular-nums">
      {decimals > 0 ? display.toFixed(decimals) : Math.round(display)}
      {suffix}
    </span>
  );
}

export function AqiGauge({ aqi, category, size = 148 }: { aqi: number; category: string; size?: number }) {
  const st = getAqiStyle(aqi);
  const stroke = 11;
  const radius = (size - stroke) / 2;
  const circumference = 2 * Math.PI * radius;
  const progress = Math.min(1, Math.max(0.03, aqi / 500));
  const dashOffset = circumference * (1 - progress * 0.78);

  return (
    <div className="relative inline-flex flex-col items-center justify-center" style={{ width: size, height: size }}>
      <svg width={size} height={size} className="-rotate-[220deg]" aria-label={`Indian AQI ${aqi}, ${category}`}>
        <circle
          cx={size / 2}
          cy={size / 2}
          r={radius}
          fill="none"
          stroke="rgba(255,255,255,0.08)"
          strokeWidth={stroke}
          strokeDasharray={`${circumference * 0.78} ${circumference}`}
          strokeLinecap="round"
        />
        <motion.circle
          cx={size / 2}
          cy={size / 2}
          r={radius}
          fill="none"
          stroke={st.color}
          strokeWidth={stroke}
          strokeDasharray={circumference}
          initial={{ strokeDashoffset: circumference }}
          animate={{ strokeDashoffset: dashOffset }}
          transition={{ duration: 0.9, ease: 'easeOut' }}
          strokeLinecap="round"
          style={{ filter: `drop-shadow(0 0 8px ${st.color}66)` }}
        />
      </svg>
      <div className="absolute inset-0 flex flex-col items-center justify-center text-center">
        <span className="font-mono text-[10px] uppercase tracking-widest text-slate-400">IN-NAQI</span>
        <span className="font-display text-4xl font-bold tracking-tight text-white tabular-nums">
          <AnimatedNumber value={aqi} />
        </span>
        <span className={cn('mt-0.5 text-xs font-semibold', st.text)}>{category}</span>
      </div>
    </div>
  );
}

